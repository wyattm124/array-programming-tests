#!/usr/bin/env python3

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import yaml

VALID_SIMD = ("NONE", "AVX2", "NEON")
OUTPUT_NAMES = {
    "NONE": "fft_bench_none.inc",
    "AVX2": "fft_bench_avx2.inc",
    "NEON": "fft_bench_neon.inc",
}


def benchmark_name(size: int, kind: str, simd: str | None = None) -> str:
    suffix = ""
    if simd is not None and (simd != "NONE" or kind == "RawFFT"):
        suffix = f" [{simd}]"
    return f"N{size}/{kind}{suffix}"


def normalize_comp_unit_raw(value: object, size: int) -> dict | None:
    if value is None:
        return None
    if isinstance(value, bool):
        return {} if value else None
    if isinstance(value, dict):
        return value
    raise ValueError(
        f"Benchmark case for size {size} must define 'comp_unit_raw' as a boolean or mapping."
    )


def normalize_fftw(value: object, size: int) -> dict | None:
    if value is None:
        return None
    if isinstance(value, bool):
        return {} if value else None
    if isinstance(value, dict):
        return value
    raise ValueError(
        f"Benchmark case for size {size} must define 'fftw' as a boolean or mapping."
    )


def normalize_variant_mapping(
    value: object, valid: tuple[str, ...], field: str, size: int
) -> dict[str, dict]:
    if value is None:
        return {}
    if isinstance(value, list):
        invalid = [item for item in value if item not in valid]
        if invalid:
            raise ValueError(
                f"Benchmark case for size {size} has invalid {field} values: {invalid}"
            )
        return {item: {} for item in value}
    if not isinstance(value, dict):
        raise ValueError(
            f"Benchmark case for size {size} must define '{field}' as a list or mapping."
        )

    invalid = sorted(set(value) - set(valid))
    if invalid:
        raise ValueError(
            f"Benchmark case for size {size} has invalid {field} keys: {invalid}"
        )

    normalized: dict[str, dict] = {}
    for key, config in value.items():
        if config is None:
            normalized[key] = {}
        elif isinstance(config, dict):
            normalized[key] = config
        else:
            raise ValueError(
                f"Benchmark case for size {size} has invalid config for {field}.{key}: {config!r}"
            )
    return normalized


def render_case(case: dict, simd: str) -> list[str]:
    if not isinstance(case, dict):
        raise ValueError("Each benchmark case must be a mapping.")

    size = case.get("size")
    if not isinstance(size, int) or size <= 0:
        raise ValueError(f"Benchmark case has invalid size: {size!r}")

    lines: list[str] = []

    comp_unit_raw = normalize_comp_unit_raw(case.get("comp_unit_raw"), size)
    if comp_unit_raw is not None and simd == "NONE":
        lines.append(
            f'    register_comp_unit_benchmark<{size}>("{benchmark_name(size, "CompUnitRaw")}");'
        )

    raw_fft = normalize_variant_mapping(case.get("raw_fft"), VALID_SIMD, "raw_fft", size)
    if simd in raw_fft:
        lines.append(
            f'    register_fft_benchmark<{size}, SIMD_TYPE::{simd}>("{benchmark_name(size, "RawFFT", simd)}");'
        )

    fftw = normalize_fftw(case.get("fftw"), size)
    if fftw is not None and simd == "NONE":
        lines.append(
            f'    register_fftw_benchmark<{size}>("{benchmark_name(size, "FFTW")}");'
        )

    return lines


def render_include(spec_path: Path, simd: str) -> str:
    with spec_path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle) or {}
    if not isinstance(data, dict):
        raise ValueError(f"{spec_path}: top-level YAML must be a mapping.")

    benchmarks = data.get("benchmarks")
    if not isinstance(benchmarks, list):
        raise ValueError(f"{spec_path}: 'benchmarks' must be a list.")

    rendered: list[str] = []
    for case in benchmarks:
        rendered.extend(render_case(case, simd))

    lines = [
        "// Generated by tools/generate_fft_benchmarks.py. Do not edit manually.",
        "// Source spec:",
        f"//   {spec_path.as_posix()}",
        "",
    ]
    if rendered:
        lines.extend(rendered)
    else:
        lines.append(f"// No benchmarks defined for SIMD_TYPE::{simd}.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", required=True)
    parser.add_argument("--out-dir", required=True)
    args = parser.parse_args()

    spec_path = Path(args.spec)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    for simd in VALID_SIMD:
        (out_dir / OUTPUT_NAMES[simd]).write_text(
            render_include(spec_path, simd), encoding="utf-8"
        )

    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise
